/* ============================================================================
   Hand-drawn overrides for the app's own pixel art.

   The rail icons and the mark are drawn in code — rect and px calls on a 16×16
   grid — which is the right default: they stay exact at any size and they can
   take a section's accent colour. But code is a clumsy way to nudge one pixel,
   and some things only look right once a person has pushed them around.

   So this file is the escape hatch. Anything with an entry here is blitted
   verbatim instead of being drawn, and anything without one falls through to
   the code as before. It is generated by tools/icon-studio.html — a private,
   local-only editor that is not part of the published site — so it is meant to
   be overwritten wholesale rather than edited by hand, though the format is
   plain enough to read in a diff.

   One consequence worth knowing: a hand-drawn icon carries its own literal
   colours, so it no longer tints itself with its section's accent. That is the
   trade for exact control, and it only matters if you later change a section's
   accent and expect its icon to follow.

   Format — one entry per piece:
     palette  the colours used, '#rrggbb' or '#rrggbbaa'
     rows     one string per row, one character per pixel:
              '.' is transparent, and 0-9 A-Z a-z index the palette.
   ========================================================================= */

