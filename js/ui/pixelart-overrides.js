/* The index alphabet. '.' is transparent so an empty row reads as empty. */
const ALPHABET = '.0123456789ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz';

export const alphabetIndex = i => ALPHABET[i + 1];
export const MAX_PALETTE = ALPHABET.length - 1;

const cache = new Map();

/** Parse '#rgb', '#rrggbb' or '#rrggbbaa' into [r,g,b,a]. */
function parseHex(hex) {
  let h = String(hex).replace('#', '').trim();
  if (h.length === 3) h = h.split('').map(c => c + c).join('');
  if (h.length === 6) h += 'ff';
  if (h.length !== 8) return [0, 0, 0, 0];
  return [0, 2, 4, 6].map(i => parseInt(h.slice(i, i + 2), 16));
}

/**
 * The hand-drawn art for a key as RGBA, or null when there is none and the
 * caller should draw it in code instead.
 * @returns {{ w:number, h:number, data:Uint8ClampedArray } | null}
 */
export function overrideArt(key) {
  if (cache.has(key)) return cache.get(key);
  const entry = ART_OVERRIDES[key];
  if (!entry?.rows?.length) { cache.set(key, null); return null; }

  const h = entry.rows.length;
  const w = entry.rows[0].length;
  const colors = (entry.palette || []).map(parseHex);
  const data = new Uint8ClampedArray(w * h * 4);
  for (let y = 0; y < h; y++) {
    const row = entry.rows[y];
    for (let x = 0; x < w; x++) {
      const idx = ALPHABET.indexOf(row[x] ?? '.') - 1;
      const c = idx >= 0 ? colors[idx] : null;
      if (!c) continue;
      const i = (y * w + x) * 4;
      data[i] = c[0]; data[i + 1] = c[1]; data[i + 2] = c[2]; data[i + 3] = c[3];
    }
  }
  const out = { w, h, data };
  cache.set(key, out);
  return out;
}

export const hasOverride = key => !!ART_OVERRIDES[key]?.rows?.length;

/** Forget a decoded entry. Only the icon studio needs this, when it takes an
 *  override away and wants to see the code-drawn version again. */
export function clearOverrideCache(key) {
  if (key === undefined) cache.clear(); else cache.delete(key);
}

/**
 * Blit one of these onto a context at a whole-number scale. Drawn as filled
 * rectangles rather than a scaled putImageData so the edges stay hard.
 */
export function blitArt(g, art, scale) {
  const { w, h, data } = art;
  for (let y = 0; y < h; y++) {
    for (let x = 0; x < w; x++) {
      const i = (y * w + x) * 4;
      const a = data[i + 3];
      if (!a) continue;
      g.fillStyle = a === 255
        ? `rgb(${data[i]},${data[i + 1]},${data[i + 2]})`
        : `rgba(${data[i]},${data[i + 1]},${data[i + 2]},${(a / 255).toFixed(3)})`;
      g.fillRect(x * scale, y * scale, scale, scale);
    }
  }
}
