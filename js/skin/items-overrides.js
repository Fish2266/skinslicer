const SYM = '0123456789ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz';
const W = 64, H = 64;

function parseHex(hex) {
  let h = String(hex).replace('#', '').trim();
  if (h.length === 6) h += 'ff';
  if (h.length !== 8) return [0, 0, 0, 0];
  return [0, 2, 4, 6].map(i => parseInt(h.slice(i, i + 2), 16));
}

/**
 * An entry's sheet for an arm width, decoded — or null when there is none
 * and the item should be drawn in code. An entry with only one width is used
 * for both.
 * @returns {{ data: Uint8ClampedArray, map: Int8Array, groups: {name, hex}[] } | null}
 */
export function itemSheet(entry, model = 'classic') {
  const sheet = entry?.[model] || entry?.classic || entry?.slim;
  if (!sheet?.rows?.length) return null;
  const cell = sheet.cell === 2 ? 2 : 1;
  const colours = sheet.palette.map(([hex, g]) => ({ rgba: parseHex(hex), g: g ?? -1 }));
  const data = new Uint8ClampedArray(W * H * 4);
  const map = new Int8Array(W * H).fill(-1);
  for (let y = 0; y < H; y++) {
    const row = sheet.rows[y] || '';
    for (let x = 0; x < W; x++) {
      const code = row.slice(x * cell, x * cell + cell);
      if (!code || code[0] === '.') continue;
      const idx = cell === 1 ? SYM.indexOf(code) : SYM.indexOf(code[0]) * SYM.length + SYM.indexOf(code[1]);
      const c = colours[idx];
      if (!c) continue;
      const i = y * W + x;
      data.set(c.rgba, i * 4);
      map[i] = c.g;
    }
  }
  return { data, map, groups: (entry.groups || []).map(([name, hex]) => ({ name, hex })) };
}

/**
 * RGBA and a group per pixel, in this file's format. The studio writes
 * with this; nothing in the app needs it.
 */
export function encodeSheet(rgba, group) {
  const palette = [];
  const index = new Map();
  const codes = new Int32Array(W * H).fill(-1);
  for (let i = 0; i < W * H; i++) {
    const a = rgba[i * 4 + 3];
    if (!a) continue;
    const hex = '#' + [rgba[i * 4], rgba[i * 4 + 1], rgba[i * 4 + 2]].map(n => n.toString(16).padStart(2, '0')).join('')
      + (a === 255 ? '' : a.toString(16).padStart(2, '0'));
    const g = group ? group[i] : -1;
    const key = `${hex}|${g}`;
    if (!index.has(key)) { index.set(key, palette.length); palette.push([hex, g]); }
    codes[i] = index.get(key);
  }
  if (palette.length > SYM.length * SYM.length) throw new Error(`${palette.length} colours is more than a sheet can hold.`);
  const cell = palette.length <= SYM.length ? 1 : 2;
  const rows = [];
  for (let y = 0; y < H; y++) {
    let row = '';
    for (let x = 0; x < W; x++) {
      const c = codes[y * W + x];
      row += c < 0 ? '.'.repeat(cell) : cell === 1 ? SYM[c] : SYM[Math.floor(c / SYM.length)] + SYM[c % SYM.length];
    }
    rows.push(row);
  }
  return { cell, palette, rows };
}
