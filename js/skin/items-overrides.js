/* ============================================================================
   Hand-drawn wardrobe items.

   The preset wardrobe is drawn in code (items.js) — the right default: every
   item is drawn per arm width and in named colour groups, so it tints
   exactly. But code is a clumsy way to push pixels around, and some items
   only look right once a person has drawn them.

   So this file is the escape hatch, as pixelart-overrides.js is for the
   icons. An entry here redraws a preset, renames it, moves it to another
   shelf or leaves it out of the wardrobe — or adds an item that has no
   drawing in code at all. Anything without an entry is drawn in code as
   before. It is generated by tools/icon-studio.html — a private, local-only
   editor that is not part of the published site — so it is meant to be
   overwritten wholesale rather than edited by hand, though the format is
   plain enough to read in a diff.

   Format — one entry per item, keyed by its id:
     name, cat      what it is called, and which shelf it is on
     view           'back' to show its tile from behind (optional)
     hidden         true to leave it out of the wardrobe (optional)
     groups         [name, reference colour] per colour group — what tints as one
     classic, slim  the 64×64 skin sheet for each arm width:
       cell     characters per pixel: 1, or 2 when there are more colours
                than one character can count
       palette  [colour, group] pairs, '#rrggbb' or '#rrggbbaa'
       rows     64 strings; '.' (or '..') is transparent, and anything else
                indexes the palette in 0-9 A-Z a-z
   ========================================================================= */

